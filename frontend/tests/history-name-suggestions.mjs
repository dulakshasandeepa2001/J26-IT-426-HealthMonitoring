// Execute the real TypeScript suggestion helper without Django or patient data.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';

const source = readFileSync(new URL('../src/features/prescription-intelligence/historyNameSuggestions.ts', import.meta.url), 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { prepareHistoryClarification, clarificationValid } = await import('data:text/javascript;base64,' + Buffer.from(js).toString('base64'));
const product = { id: 'fictional-paracetamol', name: 'Paracetamol', strength: '500 mg', form: 'tablet', route: 'oral', identity_hash: 'a'.repeat(64), aliases: ['Paracetamol 500 mg tablet'] };
const options = { version: 'test-version', allergens: ['penicillin', 'paracetamol'], products: [product] };
const raw = { allergies: ['Penicillin (Rash)'], medicines: ['Paracetamol 500mg SOS'] };
const prepared = prepareHistoryClarification(raw.allergies, raw.medicines, options);
assert.equal(prepared.allergies[0].identity, 'penicillin');
assert.equal(prepared.allergies[0].reaction, 'Rash');
assert.equal(prepared.allergies[0].reaction_date, null, 'No reaction date is invented');
assert.equal(prepared.medicines[0].catalogue_id, '', 'Strength and schedule alone never imply an exact product');
assert.equal(prepared.medicines[0].schedule, '', 'No schedule is inferred from prose');
assert.equal(prepared.medicines[0].recorded_text, raw.medicines[0]);
assert.equal(clarificationValid(prepared, options), true, 'Unresolved identities can be saved without claiming safety');
const chosen = structuredClone(prepared);
Object.assign(chosen.medicines[0], { catalogue_id: product.id, expected_identity_hash: product.identity_hash });
assert.equal(clarificationValid(chosen, options), false, 'A non-exact name requires actual clarification notes');
chosen.medicines[0].clarification_note = 'Patient confirmed the exact tablet product.';
chosen.medicines[0].schedule = 'Reported as needed';
chosen.allergies[0].reaction_date = '2020-01-01';
assert.equal(clarificationValid(chosen, options), true);
const saved = { version: options.version, reviewed_by: 123, reviewed_at: '2026-10-18T00:00:00Z', details: chosen };
assert.deepEqual(prepareHistoryClarification(raw.allergies, raw.medicines, options, saved), chosen, 'Retain bound reactions, dates, schedule and prior notes');
const extended = prepareHistoryClarification([...raw.allergies, 'Unlisted allergy'], raw.medicines, options, saved);
assert.deepEqual(extended.allergies[0], chosen.allergies[0], 'Adding a history item preserves unchanged recorded reaction details');
assert.deepEqual(extended.medicines[0], chosen.medicines[0], 'Adding an allergy does not erase a still-current product clarification');
const stale = prepareHistoryClarification(raw.allergies, raw.medicines, { ...options, products: [{ ...product, identity_hash: 'b'.repeat(64) }] }, saved);
assert.equal(stale.medicines[0].catalogue_id, '', 'A changed product identity returns to unresolved');
assert.equal(stale.medicines[0].schedule, chosen.medicines[0].schedule);
const exact = prepareHistoryClarification([], product.aliases, options);
assert.equal(exact.medicines[0].catalogue_id, product.id);
assert.equal(clarificationValid(exact, options), true);
const ambiguous = prepareHistoryClarification([], product.aliases, { ...options, products: [product, { ...product, id: 'other-product' }] });
assert.equal(ambiguous.medicines[0].catalogue_id, '', 'Multiple exact matches require explicit resolution');
const unknown = prepareHistoryClarification(['Unlisted allergy'], ['Unlisted medicine'], options, saved);
assert.equal(unknown.allergies[0].identity, '');
assert.equal(unknown.allergies[0].reaction_date, null);
assert.equal(unknown.medicines[0].catalogue_id, '');
assert.equal(unknown.medicines[0].schedule, '', 'Old resolutions never leak to different raw history');
assert.deepEqual(raw, { allergies: ['Penicillin (Rash)'], medicines: ['Paracetamol 500mg SOS'] }, 'Suggestion preparation never edits source history');
assert.equal('reviewed_by' in prepared, false, 'The UI never fabricates reviewer provenance');
console.log('PASS: exact-only proposals, unknowns, ambiguity, stale bindings, retained original history, and clarification-note requirements.');
